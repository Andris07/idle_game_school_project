import { fetchDb, postDb, putDbById } from "./data.js";
import { addMoney, spendMoney } from "./money.js";
import { refreshInventory, isInventoryFull, getFreeInventorySlots } from "./app.js";
import { showMessagePopup } from "./popup.js";
import { loadEventTypes, queueEvent, startPendingEvent, isEventBusy, onEventChange, getShapeCopies, formatEventDuration } from "./events.js";
import { checkGameOver } from "./gameover.js";
import { recordChest } from "./stats.js";

const SHAPE_CHEST_COST = 100;
const UPGRADE_CHEST_COST = 2500;
const BUFF_CHEST_COST = 5000;
const UPGRADE_MIN = 10;
const UPGRADE_MAX = 50;

const shapeChestButton = document.querySelector("#shape-chest-button");
const upgradeChestButton = document.querySelector("#upgrade-chest-button");
const buffChestButton = document.querySelector("#buff-chest-button");

shapeChestButton.textContent = `${SHAPE_CHEST_COST} $`;
upgradeChestButton.textContent = `${UPGRADE_CHEST_COST} $`;
buffChestButton.textContent = `${BUFF_CHEST_COST} $`;

function randomInt(min, max)
{
    return min + Math.floor(Math.random() * (max - min + 1));
}

// every result is shown in a popup and also logged to the console
function showResult(chestName, lines)
{
    console.warn(`${chestName}: ${lines.join(" | ")}`);
    showMessagePopup(chestName, lines);
}

function showError(chestName, message)
{
    console.warn(`${chestName}: ${message}`);
    showMessagePopup(chestName, [message], true);
}

async function refund(cost)
{
    try
    {
        await addMoney(cost);
    }
    catch (refundError)
    {
        console.error("Could not refund chest cost: ", refundError);
    }
}

// Shape Chest: a random shape goes to the inventory, its value is based on the CURRENT base_value of the shape
shapeChestButton.addEventListener("click", async () =>
{
    if (isInventoryFull()) return;

    shapeChestButton.disabled = true;
    let shouldRefund = false;

    try
    {
        // shapes are always loaded from the server (not from the cache of app.js), so upgraded base_values are used
        const shapes = await fetchDb("SHAPE");
        const shape = shapes[Math.floor(Math.random() * shapes.length)];

        if (!await spendMoney(SHAPE_CHEST_COST))
        {
            showError("Shape Chest", `Not enough money! You need ${SHAPE_CHEST_COST} $ to open this chest.`);
            return;
        }

        shouldRefund = true;

        const value = Number(shape.base_value) + (5 + Math.floor(Math.random() * 5) + 1);

        // Double Shape event: the shape comes with identical copies (as many as the inventory has room for)
        const copies = Math.max(1, Math.min(getShapeCopies(), getFreeInventorySlots()));

        // id is generated by the database, so we don't need to calculate it here
        for (let copy = 0; copy < copies; copy += 1)
        {
            await postDb("INVENTORY_ITEM", { shape_id: shape.id, value });
            shouldRefund = false; // the player got a shape, so the chest is paid for
        }

        shouldRefund = false;
        await recordChest("shape");
        await refreshInventory();
    }
    catch (error)
    {
        console.error("Could not save inventory item: ", error);
        showError("Shape Chest", "Could not open the chest, the server is not reachable.");

        if (shouldRefund) await refund(SHAPE_CHEST_COST);
    }
    finally
    {
        // also after an error: a copy may have been saved before the failure
        await refreshInventory().catch((error) => console.error("Could not refresh inventory: ", error));
        shapeChestButton.disabled = isInventoryFull();
    }

    // the new shape may be one that cannot be placed anywhere
    await checkGameOver();
});

// Upgrade Chest: the base_value of a random base shape is increased by 10-50 on the server.
// Only shapes created after this are affected, existing inventory items and placements keep their own value.
upgradeChestButton.addEventListener("click", async () =>
{
    upgradeChestButton.disabled = true;
    let shouldRefund = false;

    try
    {
        const shapes = await fetchDb("SHAPE");
        const shape = shapes[Math.floor(Math.random() * shapes.length)];
        const increase = randomInt(UPGRADE_MIN, UPGRADE_MAX);
        const oldValue = Number(shape.base_value) || 0;
        const newValue = oldValue + increase;

        if (!await spendMoney(UPGRADE_CHEST_COST))
        {
            showError("Upgrade Chest", `Not enough money! You need ${UPGRADE_CHEST_COST} $ to open this chest.`);
            return;
        }

        shouldRefund = true;

        await putDbById("SHAPE", shape.id, { ...shape, base_value: newValue });

        shouldRefund = false;
        await recordChest("upgrade");

        showResult("Upgrade Chest",
        [
            `${shape.name.toUpperCase()} shape upgraded!`,
            `Base value: ${oldValue} $ → ${newValue} $ (+${increase} $)`,
            "Only newly opened shapes are affected.",
        ]);
    }
    catch (error)
    {
        console.error("Could not upgrade shape: ", error);
        showError("Upgrade Chest", "Could not upgrade a shape, the server is not reachable.");

        if (shouldRefund) await refund(UPGRADE_CHEST_COST);
    }
    finally
    {
        upgradeChestButton.disabled = false;
    }
});

// Buff Chest: opens ONE of the 4 quick time events (25% each). The event is not saved to the inventory, it is used right away:
// the popup shows what was opened, and the timer starts when the popup is closed (events.js).
buffChestButton.addEventListener("click", async () =>
{
    if (isEventBusy()) return;

    buffChestButton.disabled = true;
    let shouldRefund = false;

    try
    {
        // the durations come from the EVENT_TYPE table of the database
        const types = await loadEventTypes();

        if (types.length === 0) throw new Error("No quick time event is available");

        // every event has the same chance (1 / number of events = 25% with the 4 events of the game)
        const type = types[Math.floor(Math.random() * types.length)];

        if (!await spendMoney(BUFF_CHEST_COST))
        {
            showError("Buff Chest", `Not enough money! You need ${BUFF_CHEST_COST} $ to open this chest.`);
            return;
        }

        shouldRefund = true;

        const definition = await queueEvent(type);

        shouldRefund = false;
        await recordChest("buff");

        showMessagePopup("Buff Chest",
        [
            definition.description,
            `Duration: ${formatEventDuration(Number(type.duration_seconds))}`,
            "The timer starts when you close this window.",
        ],
        false,
        {
            icon: definition.icon,
            highlight: definition.title,
            onClose: () => startPendingEvent(),
        });
    }
    catch (error)
    {
        console.error("Could not open the buff chest: ", error);
        showError("Buff Chest", "Could not open the chest, the server is not reachable.");

        if (shouldRefund) await refund(BUFF_CHEST_COST);
    }
    finally
    {
        updateBuffChestButton();
    }
});

// only one event can be opened at a time, so the chest is locked while one is opened or running
function updateBuffChestButton()
{
    buffChestButton.disabled = isEventBusy();
    buffChestButton.title = isEventBusy() ? "A quick time event is already running" : "";
}

onEventChange(updateBuffChestButton);
updateBuffChestButton();
